// Mock portfolio history for charts
export function generateMockPortfolioHistory(days = 30) {
  const timestamps: number[] = [];
  const equity: number[] = [];
  const profitLoss: number[] = [];

  const now = Date.now();
  let currentEquity = 260000;

  for (let i = days; i >= 0; i--) {
    const ts = now - i * 24 * 60 * 60 * 1000;
    timestamps.push(Math.floor(ts / 1000));

    const dailyReturn = (Math.random() - 0.48) * 0.02;
    currentEquity *= 1 + dailyReturn;
    equity.push(Math.round(currentEquity * 100) / 100);
    profitLoss.push(Math.round((currentEquity - 260000) * 100) / 100);
  }

  return { timestamps, equity, profitLoss };
}
